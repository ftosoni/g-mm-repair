# End-to-end manuscript reproduction (run on the GB10 node).
#
#   raw experiment output  ->  manuscript/logs/<experiment>.log   (kept, never overwritten in place
#                                                        without a provenance header)
#                          ->  extract_results.py       ->  manuscript/tables/*.tex
#                                                            manuscript/figures/data/*.dat
#                          ->  pdflatex fig_*.tex        ->  manuscript/figures/fig_*.pdf
#
# Every canonical log uses "## <key>" block markers (one per dataset/config) so a single
# parser (extract_results.py) can slice it. Each log starts with a provenance header
# (date, host, git commit) so a stale rerun is always attributable.
#
# Usage:
#   ./reproduce.sh all        # run every experiment family, then extract + plot
#   ./reproduce.sh struct     # only the (cheap, node-independent) structural logs
#   ./reproduce.sh grammar    # capture RePair grammar-build times (EXPENSIVE; not in `all`)
#   ./reproduce.sh extract    # skip experiments; just re-extract tables/figures from logs
#   ./reproduce.sh graphscale # tab:graph_scale, largest two Wikidata relations (heavy)
#   ./reproduce.sh crosscheck # cross-implementation correctness across all table columns (heavy)
#   ./reproduce.sh <family>   # one of: struct grammar time space spmm graph graphscale crosscheck extract plot
set -uo pipefail

cd "$(dirname "$0")"
export PATH=/usr/local/cuda/bin:$PATH
# Canonical logs live under manuscript/logs/ (gitignored), co-located with the
# tables/figures they feed. extract_results.py reads from the same directory.
LOGS=manuscript/logs
mkdir -p "$LOGS" manuscript/tables manuscript/figures/data

GPU=./gpu-engine/gpu_test
CUS=./gpu-engine/cusparse_test

# Datasets live in the Zenodo data package (doi:10.5281/zenodo.XXXXXXX), extracted
# into a subfolder of this repo -- by default ./zenodo/{genotypes,wikidata,swh}/ (the
# record's own layout). Override with e.g. ZENODO_DIR=/path/to/package if you keep it
# elsewhere. Each stem <ZENODO_DIR>/<cat>/<base> resolves both the grammar the engine
# reads (<base>.vc.C, .vc.R, .val) and, once you run `zstd -d <base>.zst`, the dense
# matrix that the grammar/space stages rebuild from.
ZENODO_DIR=${ZENODO_DIR:-zenodo}

# key path rows cols
GENO=(
  "geno22|$ZENODO_DIR/genotypes/geno22|2504|100000"
  "geno22full|$ZENODO_DIR/genotypes/geno22full|2504|1055454"
  "geno21|$ZENODO_DIR/genotypes/geno21|2504|100000"
  "geno21full|$ZENODO_DIR/genotypes/geno21full|2504|1054447"
  "geno20|$ZENODO_DIR/genotypes/geno20|2504|100000"
  "geno20full|$ZENODO_DIR/genotypes/geno20full|2504|1739315"
  "geno_synth_small|$ZENODO_DIR/genotypes/geno_synth_small|2000|50000"
  "geno_synth_large|$ZENODO_DIR/genotypes/geno_synth_large|5000|200000"
  "geno_synth_ld_high|$ZENODO_DIR/genotypes/geno_synth_ld_high|5000|100000"
  "geno_synth_ld_low|$ZENODO_DIR/genotypes/geno_synth_ld_low|5000|100000"
  "geno_synth_ind_large|$ZENODO_DIR/genotypes/geno_synth_ind_large|10000|50000"
)
CROSSOVER="crossover_synth|$ZENODO_DIR/genotypes/crossover_synth|10000|700000"

# key path rows cols   (Wikidata relations; sparse edge list + grammar in the package)
GRAPH=(
  "wd_sports_team|$ZENODO_DIR/wikidata/wd_sports_team|332121|29854"
  "wd_cast_member|$ZENODO_DIR/wikidata/wd_cast_member|173977|144095"
  "wd_citizenship|$ZENODO_DIR/wikidata/wd_citizenship|2874250|2556"
  "wd_occupation|$ZENODO_DIR/wikidata/wd_occupation|3459933|10610"
  "wd_subclass_of|$ZENODO_DIR/wikidata/wd_subclass_of|1487709|73417"
)
# Largest relations (tab:graph_scale); wd_cites_work (166M) and swh_full (1.22G) are heavy.
GRAPH_SCALE=(
  "wd_country|$ZENODO_DIR/wikidata/wd_country|10058956|1747"
  "wd_cites_work|$ZENODO_DIR/wikidata/wd_cites_work|7072574|12245945"
  "swh_full|$ZENODO_DIR/swh/swh_full|45691499|45691499"
)

prov() {   # prov <logfile>  -- write a provenance header, truncating the log
  local f=$1
  {
    echo "# GENERATED by reproduce.sh -- raw experiment log, parsed by extract_results.py"
    echo "# date:   $(date -Is)"
    echo "# host:   $(hostname)  ($(uname -srm))"
    echo "# commit: $(git rev-parse --short HEAD 2>/dev/null || echo unknown)"
  } > "$f"
}

# ---- structural figures (Table 1 / Table 5): cheap, node-independent -----------------
run_struct() {
  local log=$LOGS/geno_struct.log; prov "$log"
  for e in "${GENO[@]}"; do IFS='|' read -r key path r c <<<"$e"
    echo "## $key" | tee -a "$log"
    $GPU "$path" "$r" "$c" 1 repair 2>&1 | tee -a "$log"
  done
  local glog=$LOGS/graph_struct.log; prov "$glog"
  for e in "${GRAPH[@]}"; do IFS='|' read -r key path r c <<<"$e"
    echo "## $key" | tee -a "$glog"
    $GPU "$path" "$r" "$c" 1 repair 2>&1 | tee -a "$glog"
  done
}

# ---- Table B grammar column: RePair construction cost (offline mm-repair) ------------
# Captures matrepair's "Compression Report" per genotype grammar. Uses -r (full report)
# WITHOUT -y, so it does a full rebuild for a real timing; the build is deterministic
# (single block, --i32) and rewrites identical files, so it is safe to run in place. This
# recompresses the grammars, so it is EXPENSIVE and kept out of `all`; run it once to
# populate the grammar-build times.
#
# NOTE ON PARALLELISM (verified in mm-repair/matrepair): -p parallelizes irepair ONLY
# ACROSS -b row-blocks and is hard-capped at -b (matrepair lines 75-77). The genotype
# grammars are single-block (-b 1) -- the exact grammar the engine reads (one .vc.C) and
# the one profiled in every other table -- so -p has no effect and this build is inherently
# SEQUENTIAL. We deliberately time the sequential single-block build; using -b>1 would
# time a structurally different multi-block grammar, not the one benchmarked elsewhere.
run_grammar() {
  local log=$LOGS/grammar_build.log; prov "$log"
  for e in "${GENO[@]}"; do IFS='|' read -r key path r c <<<"$e"
    echo "## $key" | tee -a "$log"
    ./mm-repair/matrepair -r --i32 "$path" "$r" "$c" 2>&1 | tee -a "$log"   # -b 1, sequential (see note)
  done
}

# ---- Table 2 (times): reuse the existing CSV-producing driver ------------------------
run_time() { bash run_all_bio_baselines.sh; }   # writes $LOGS/bio_results.csv

# ---- Table 3 + fig:space (space/energy vs cuSPARSE, incl. crossover OOM) --------------
run_space() {
  local log=$LOGS/geno_space_energy.log; prov "$log"
  for e in "${GENO[@]}" "$CROSSOVER"; do IFS='|' read -r key path r c <<<"$e"
    echo "## $key" | tee -a "$log"
    $GPU "$path" "$r" "$c" 100 repair 2>&1 | tee -a "$log"
    echo "--- CUSPARSE ---" | tee -a "$log"
    $CUS "$path" "$r" "$c" 100 2>&1 | tee -a "$log"    # may OOM on crossover -> logged
  done
}

# ---- Table 4 + fig:batched (batched SpMM sweep, engine + cuSPARSE alg sweep) ----------
run_spmm() {
  local elog=$LOGS/geno_spmm.log; prov "$elog"
  local clog=$LOGS/geno_cusparse_alg.log; prov "$clog"
  for e in "${GENO[@]}"; do IFS='|' read -r key path r c <<<"$e"
    echo "## $key" | tee -a "$elog"; echo "## $key" | tee -a "$clog"
    for B in 16 32 64 128 256; do
      $GPU "$path" "$r" "$c" 50 repair "$B" 2>&1 | tee -a "$elog"
      $CUS "$path" "$r" "$c" 50 repair "$B" 2>&1 | tee -a "$clog"   # sweeps default/alg2/alg3
    done
  done
}

# ---- Table 6 (Boolean/Tropical graph product + GraphBLAS baseline) --------------------
run_graph() {
  local log=$LOGS/graph_semiring.log; prov "$log"
  for e in "${GRAPH[@]}"; do IFS='|' read -r key path r c <<<"$e"
    for sr in boolean tropical; do
      echo "## ${key}_${sr}" | tee -a "$log"
      SEMIRING=$sr $GPU "$path" "$r" "$c" 50 repair 16 2>&1 | tee -a "$log"
      if [ -f "${path}.sparse" ]; then
        ./gbvenv/bin/python graphblas_bench.py "${path}.sparse" "$r" "$c" \
          "$([ "$sr" = boolean ] && echo bool || echo tropical)" 50 2>&1 | tee -a "$log"
      fi
      [ "$sr" = boolean ] && $CUS "$path" "$r" "$c" 50 2>&1 | tee -a "$log"
    done
  done
}

# ---- tab:graph_scale (largest two Wikidata relations) --------------------------------
# Boolean single-vector engine + cuSPARSE, plus the serialized REANS size. Uses
# matrepair -r -y (lazy): -y skips the compression phases and just prints the size report
# ("REANS size: N bytes") from the existing grammar -- fast, no rebuild. Kept out of `all`
# because wd_cites_work (166M edges) is a heavy scale run.
run_graphscale() {
  local log=$LOGS/graph_scale.log; prov "$log"
  for e in "${GRAPH_SCALE[@]}"; do IFS='|' read -r key path r c <<<"$e"
    echo "## $key" | tee -a "$log"
    SEMIRING=boolean $GPU "$path" "$r" "$c" 50 repair 2>&1 | tee -a "$log"
    echo "--- CUSPARSE ---" | tee -a "$log"
    $CUS "$path" "$r" "$c" 50 2>&1 | tee -a "$log"
    echo "--- GRAMMAR ---" | tee -a "$log"
    ./mm-repair/matrepair -r -y --bool "$path" "$r" "$c" 2>&1 | tee -a "$log"
  done
}

# ---- cross-implementation correctness (sec:setup "Correctness") ------------------------
# For each dataset/semiring the engine dumps the SHARED input vector x and its output y;
# every algorithm/config that appears as a COLUMN of tab:geno_time / tab:geno_spmm /
# tab:graph / tab:graph_scale then recomputes y on that same x and must agree:
#   plustimes (tab:geno_time/spmm): engine, CPU seq, CPU OpenMP, cuSPARSE (SpMV+SpMM),
#                                   CPU CSR SpMV, mm-repair re32mm; engine/cuSPARSE batched B=16
#   boolean  (tab:graph/scale)    : engine, CPU seq, CPU OpenMP, cuSPARSE, CPU CSR SpMV,
#                                   GraphBLAS lor_land; engine batched B=16
#   tropical (tab:graph)          : engine, CPU seq, CPU OpenMP, CPU CSR min-plus,
#                                   GraphBLAS min_plus; engine batched B=16
# The full 1.22G-edge swh_full is included (Boolean) with FORCE_CPU_VERIFY=1, so the CPU
# oracle runs there too and the engine is certified bit-for-bit at billion-edge scale.
run_crosscheck() {
  local log=$LOGS/crosscheck.log
  { echo "# GENERATED by reproduce.sh crosscheck -- cross-implementation correctness log"
    echo "# date:   $(date -Is)"
    echo "# host:   $(hostname)  ($(uname -srm))"
    echo "# commit: $(git rev-parse --short HEAD 2>/dev/null || echo unknown)"; } > "$log"
  local tmp; tmp=$(mktemp -d)
  local RE32=./mm-repair/re32mm
  [ -x "$RE32" ] || cc -std=c99 -O3 -o "$RE32" mm-repair/remm.c -pthread 2>/dev/null || true

  # -- plustimes genotypes (tab:geno_time / tab:geno_spmm) --
  for e in "${GENO[@]}" "$CROSSOVER"; do IFS='|' read -r key path r c <<<"$e"
    [ -f "${path}.vc.C" ] || { echo "## ${key}_plustimes  (SKIP: no grammar)" | tee -a "$log"; continue; }
    local P=$tmp/$key
    echo "## ${key}_plustimes" | tee -a "$log"
    CROSSCHECK=$P SEMIRING=plustimes $GPU "$path" "$r" "$c" 1 repair 16 >>"$log" 2>&1   # dump + single/OpenMP/batched verify
    CROSSCHECK=$P SEMIRING=plustimes $CUS "$path" "$r" "$c" 1           >>"$log" 2>&1   # cuSPARSE + CPU CSR SpMV vs engine
    $CUS "$path" "$r" "$c" 20 repair 16 >>"$log" 2>&1 || true                          # cuSPARSE SpMM batched (own identical x)
    if [ -x "$RE32" ] && [ -f "${path}.val" ] && [ -f "$P.plustimes.x" ]; then         # mm-repair re32mm column
      ./gbvenv/bin/python -c "import numpy as np; np.fromfile('$P.plustimes.x',dtype=np.float32).astype(np.float64).tofile('$P.xd')" 2>>"$log" \
        && "$RE32" -y "$P.remm.y" "$path" "$r" "$c" "$P.xd" >>"$log" 2>&1 \
        && ./gbvenv/bin/python crosscheck_compare.py remm "$P.remm.y" "$P.plustimes.y" >>"$log" 2>&1
    fi
    rm -f "$P".*.x "$P".*.y "$P".xd "$P".remm.y
  done

  # -- boolean + tropical graph relations (tab:graph) --
  for e in "${GRAPH[@]}"; do IFS='|' read -r key path r c <<<"$e"
    [ -f "${path}.vc.C" ] || { echo "## ${key}  (SKIP: no grammar)" | tee -a "$log"; continue; }
    for sr in boolean tropical; do
      local P=$tmp/${key}_$sr
      echo "## ${key}_${sr}" | tee -a "$log"
      CROSSCHECK=$P SEMIRING=$sr $GPU "$path" "$r" "$c" 1 repair 16 >>"$log" 2>&1       # dump + single/OpenMP/batched verify
      CROSSCHECK=$P SEMIRING=$sr $CUS "$path" "$r" "$c" 1           >>"$log" 2>&1       # cuSPARSE/CPU CSR (bool) or CPU min-plus (trop)
      if [ -f "${path}.sparse" ]; then
        CROSSCHECK=$P SEMIRING=$sr ./gbvenv/bin/python graphblas_bench.py \
          "${path}.sparse" "$r" "$c" "$([ "$sr" = boolean ] && echo bool || echo tropical)" >>"$log" 2>&1
      fi
      rm -f "$P".*.x "$P".*.y
    done
  done

  # -- largest Boolean relations (tab:graph_scale), incl. the full 1.22G-edge SWH graph --
  for e in "${GRAPH_SCALE[@]}"; do IFS='|' read -r key path r c <<<"$e"
    [ -f "${path}.vc.C" ] || { echo "## ${key}_boolean  (SKIP: no grammar)" | tee -a "$log"; continue; }
    local P=$tmp/${key}_boolean
    echo "## ${key}_boolean" | tee -a "$log"
    FORCE_CPU_VERIFY=1 CROSSCHECK=$P SEMIRING=boolean $GPU "$path" "$r" "$c" 1 repair >>"$log" 2>&1  # engine vs CPU seq+OpenMP (bit-for-bit) + dump
    CROSSCHECK=$P SEMIRING=boolean $CUS "$path" "$r" "$c" 1        >>"$log" 2>&1                      # cuSPARSE + CPU CSR SpMV vs engine
    if [ -f "${path}.sparse" ]; then
      CROSSCHECK=$P SEMIRING=boolean ./gbvenv/bin/python graphblas_bench.py "${path}.sparse" "$r" "$c" bool >>"$log" 2>&1
    fi
    rm -f "$P".*.x "$P".*.y
  done

  rm -rf "$tmp"
  echo "crosscheck: $(grep -c SUCCESS "$log") SUCCESS, $(grep -Ec 'FAILURE|mismatches=[1-9]|FAIL$' "$log") failures -> $log"
}

# ---- extract + plot ------------------------------------------------------------------
run_extract() { python3 extract_results.py; }
run_plot() {
  ( cd manuscript/figures && for f in fig_space fig_batched; do
      pdflatex -interaction=nonstopmode -halt-on-error "$f.tex" >/dev/null 2>&1 \
        && echo "  [ok]  figures/$f.pdf" || echo "  [ERR] figures/$f.tex failed to compile"
      rm -f "$f.aux" "$f.log"
    done )
}

case "${1:-all}" in
  struct)  run_struct ;;
  grammar) run_grammar ;;
  time)    run_time ;;
  space)   run_space ;;
  spmm)    run_spmm ;;
  graph)   run_graph ;;
  graphscale) run_graphscale ;;
  crosscheck) run_crosscheck ;;
  extract) run_extract ;;
  plot)    run_plot ;;
  all)     run_struct; run_time; run_space; run_spmm; run_graph; run_extract; run_plot ;;
  *) echo "usage: $0 {all|struct|grammar|time|space|spmm|graph|graphscale|crosscheck|extract|plot}"; exit 2 ;;
esac
echo "reproduce.sh: '${1:-all}' done."
